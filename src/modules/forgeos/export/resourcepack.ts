import type { ProjectContent } from "../content";
import type { TargetVersion } from "../versions";
import { getMaterial } from "../catalog";
import { customModelDataFor, hasVisual, putJson, type FileMap } from "./common";

/** Rewrites a validated uploaded model's texture names into the project namespace. */
function rewriteModel(model: Record<string, unknown>, ns: string): Record<string, unknown> {
  const textures = Object.fromEntries(Object.entries((model.textures ?? {}) as Record<string, string>).map(([k, v]) => [k, v.startsWith("#") ? v : `${ns}:item/${v}`]));
  const out: Record<string, unknown> = { ...model, textures };
  if (typeof out.parent === "string" && !out.parent.includes(":")) out.parent = `minecraft:${out.parent}`;
  return out;
}

/**
 * Generates a resource pack: textures, item models and, depending on the target,
 * item model definitions (1.21.4+) or custom_model_data overrides on the base item.
 */
export function generateResourcePack(c: ProjectContent, t: TargetVersion, textures: Map<string, Uint8Array>): FileMap {
  const files: FileMap = new Map();
  const ns = c.project.namespace;
  putJson(files, "pack.mcmeta", { pack: { pack_format: t.resourcePackFormat, description: c.pack.description || `${c.project.name} — generated by SythiX ForgeOS` } });
  if (c.pack.icon_asset_id && textures.has(c.pack.icon_asset_id)) files.set("pack.png", textures.get(c.pack.icon_asset_id)!);

  for (const asset of c.assets) {
    if (asset.kind === "texture" && textures.has(asset.id)) files.set(`assets/${ns}/textures/item/${asset.name}.png`, textures.get(asset.id)!);
  }

  const cmd = customModelDataFor(c);
  const overrides = new Map<string, { n: number; model: string }[]>();
  const assetsById = new Map(c.assets.map((a) => [a.id, a]));

  for (const item of c.items.filter(hasVisual)) {
    const mat = getMaterial(item.base_material);
    if (!mat) continue;
    const modelAsset = item.data.modelAssetId ? assetsById.get(item.data.modelAssetId) : undefined;
    const tex = item.texture_asset_id ? assetsById.get(item.texture_asset_id) : undefined;
    const model = modelAsset?.metadata.model
      ? rewriteModel(modelAsset.metadata.model as Record<string, unknown>, ns)
      : { parent: `minecraft:${mat.parent}`, textures: { layer0: `${ns}:item/${tex?.name}` } };
    putJson(files, `assets/${ns}/models/item/${item.identifier}.json`, model);

    if (t.itemModelComponent) {
      putJson(files, `assets/${ns}/items/${item.identifier}.json`, { model: { type: "minecraft:model", model: `${ns}:item/${item.identifier}` } });
    } else {
      const list = overrides.get(mat.id) ?? [];
      list.push({ n: cmd.get(item.identifier)!, model: `${ns}:item/${item.identifier}` });
      overrides.set(mat.id, list);
    }
  }

  for (const [base, list] of [...overrides.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const mat = getMaterial(base)!;
    putJson(files, `assets/minecraft/models/item/${base}.json`, {
      parent: `minecraft:${mat.parent}`,
      textures: { layer0: `minecraft:item/${base}` },
      overrides: list.sort((a, b) => a.n - b.n).map((o) => ({ predicate: { custom_model_data: o.n }, model: o.model })),
    });
  }
  return files;
}
