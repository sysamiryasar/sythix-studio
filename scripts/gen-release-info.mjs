// Generates src/generated/release.ts from package.json and CHANGELOG.md so the
// Studio updates page reports the exact version and changelog that was built.
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { execSync } from "node:child_process";

const pkg = JSON.parse(readFileSync("package.json", "utf8"));
let changelog = "";
try {
  changelog = readFileSync("CHANGELOG.md", "utf8");
} catch {
  changelog = "";
}
let commit = process.env.GITHUB_SHA || process.env.WORKERS_CI_COMMIT_SHA || "";
if (!commit) {
  try {
    commit = execSync("git rev-parse HEAD", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
  } catch {
    commit = "unknown";
  }
}
mkdirSync("src/generated", { recursive: true });
writeFileSync(
  "src/generated/release.ts",
  `// AUTO-GENERATED by scripts/gen-release-info.mjs — do not edit.\n` +
    `export const RELEASE = ${JSON.stringify({ version: pkg.version, commit, builtAt: new Date().toISOString() }, null, 2)} as const;\n` +
    `export const CHANGELOG_MD = ${JSON.stringify(changelog)};\n`,
);

// Bundle the reviewed migrations so the Worker can apply them on startup.
const migrations = readdirSync("migrations")
  .filter((f) => /^\d{4}_[a-z0-9_]+\.sql$/.test(f))
  .sort()
  .map((name) => ({ name, sql: readFileSync(`migrations/${name}`, "utf8") }));
writeFileSync(
  "src/generated/migrations.ts",
  `// AUTO-GENERATED by scripts/gen-release-info.mjs from migrations/ — do not edit.\n` +
    `export const MIGRATIONS: readonly { name: string; sql: string }[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
