// Bundles migrations/*.sql into the Worker so it can migrate D1 itself on first use.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
const files = readdirSync("migrations").filter((f) => /^\d{4}_[a-z0-9_]+\.sql$/.test(f)).sort();
const entries = files.map((name) => ({ name, sql: readFileSync(`migrations/${name}`, "utf8") }));
mkdirSync("src/worker/generated", { recursive: true });
writeFileSync(
  "src/worker/generated/migrations.ts",
  `// Generated by scripts/gen-migrations.mjs — do not edit.\nexport const MIGRATIONS: readonly { name: string; sql: string }[] = ${JSON.stringify(entries, null, 2)};\n`,
);
